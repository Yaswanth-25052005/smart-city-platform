import streamlit as st
import requests
import pandas as pd
from datetime import datetime, timezone
from dashboard.api import API_URL
from backend.config.settings import ML_ENABLED

st.set_page_config(page_title="Predictions", page_icon="🔮", layout="wide")

st.title("Machine Learning Predictions")

if not ML_ENABLED:
    st.warning("ML predictions are currently disabled. Set ML_ENABLED=true in your environment to activate them.")
    st.stop()

st.markdown("""
This page displays predictions from the ML Pipeline (Phase 8). 
Predictions are generated by `backend.ml.predict` using models trained via `backend.ml.train`.
""")

col1, col2 = st.columns(2)

with col1:
    st.subheader("Smart Parking Predictions")
    try:
        resp = requests.get(f"{API_URL}/api/predictions/latest", params={"type": "parking", "limit": 10})
        if resp.status_code == 200:
            data = resp.json()
            if data:
                df = pd.DataFrame(data)
                df['target_timestamp'] = pd.to_datetime(df['target_timestamp'])
                # Format for display
                df_display = df[['device_id', 'target_timestamp', 'predicted_value', 'model_version']]
                df_display.columns = ["Device", "Target Time", "Occupancy Probability", "Model"]
                st.dataframe(df_display, use_container_width=True)
                
                # Show the latest one clearly
                latest = data[0]
                prob = latest['predicted_value']
                st.metric("Predicted Occupancy Prob", f"{prob*100:.1f}%")
            else:
                st.info("No parking predictions available. Ensure models are trained and `predict.py` has run.")
    except Exception as e:
        st.error(f"Failed to fetch parking predictions: {e}")

with col2:
    st.subheader("Air Quality Predictions")
    try:
        resp = requests.get(f"{API_URL}/api/predictions/latest", params={"type": "air_quality", "limit": 10})
        if resp.status_code == 200:
            data = resp.json()
            if data:
                df = pd.DataFrame(data)
                df['target_timestamp'] = pd.to_datetime(df['target_timestamp'])
                # Format for display
                df_display = df[['device_id', 'target_timestamp', 'predicted_value', 'model_version']]
                df_display.columns = ["Device", "Target Time", "Predicted AQI", "Model"]
                st.dataframe(df_display, use_container_width=True)
                
                latest = data[0]
                val = latest['predicted_value']
                st.metric("Predicted Next AQI", f"{val:.1f}")
            else:
                st.info("No AQI predictions available. Ensure models are trained and `predict.py` has run.")
    except Exception as e:
        st.error(f"Failed to fetch AQI predictions: {e}")

st.markdown("---")
st.markdown("ℹ️ *Note: ML models are trained on simulator oscillations. Forecast accuracy represents pattern learning from the virtual data stream.*")
